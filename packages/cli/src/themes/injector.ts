function radiusToCss(radius?: ThemeConfig["radius"]): string {
  const map: Record<NonNullable<ThemeConfig["radius"]>, string> = {
    none: "0px",
    sm: "0.25rem",
    default: "0.5rem",
    md: "0.75rem",
    lg: "1rem",
    xl: "1.5rem",
  }
  return radius ? map[radius] : "0.5rem"
}

/**
 * 简单的颜色变暗算法（仅用于亮色主题的暗色变体生成）
 * 不处理 oklch() 等复杂值，遇到则原样返回
 */
function darkenColor(color: string): string {
  // oklch / hsl / rgb / rgba 等复杂值直接返回
  if (color.startsWith("oklch") || color.startsWith("hsl") || color.startsWith("rgb")) {
    return color
  }
  // radial-gradient / linear-gradient 等直接返回
  if (color.includes("gradient")) {
    return color
  }
  // transparent 直接返回
  if (color === "transparent") {
    return color
  }
  // hex 颜色简单变暗
  if (color.startsWith("#") && color.length === 7) {
    try {
      const r = Math.floor(parseInt(color.slice(1, 3), 16) * 0.8)
      const g = Math.floor(parseInt(color.slice(3, 5), 16) * 0.8)
      const b = Math.floor(parseInt(color.slice(5, 7), 16) * 0.8)
      return `#${r.toString(16).padStart(2, "0")}${g.toString(16).padStart(2, "0")}${b.toString(16).padStart(2, "0")}`
    } catch {
      return color
    }
  }
  return color
}
