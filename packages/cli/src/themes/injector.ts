/**
 * 生成 CSS 变量字符串（含 :root 与 .dark 双模式）
 */
export function generateThemeCssVars(theme: ThemeConfig): string {
  const lines: string[] = []

  // 亮色模式（或默认）
  lines.push(`:root[data-theme="${theme.name}"] {`)
  lines.push(`  --primary: ${theme.primaryColor};`)
  lines.push(`  --background: ${theme.backgroundColor};`)
  if (theme.accentColor) {
    lines.push(`  --accent: ${theme.accentColor};`)
  }
  if (theme.cssVars) {
    for (const [key, value] of Object.entries(theme.cssVars)) {
      lines.push(`  ${key}: ${value};`)
    }
  }
  lines.push(`  --radius: ${radiusToCss(theme.radius)};`)
  lines.push("}")
  lines.push("")

  // 暗色模式（如果是亮色主题，则提供暗色变体）
  if (!theme.darkMode) {
    lines.push(`.dark[data-theme="${theme.name}"] {`)
    lines.push(`  --primary: ${darkenColor(theme.primaryColor)};`)
    lines.push(`  --background: ${darkenColor(theme.backgroundColor)};`)
    if (theme.accentColor) {
      lines.push(`  --accent: ${darkenColor(theme.accentColor)};`)
    }
    lines.push("}")
  }

  return lines.join("\n")
}

/**
 * 生成 Tailwind 配置片段
 */
export function generateTailwindConfig(theme: ThemeConfig): string {
  const colors: Record<string, string> = {
    primary: "var(--primary)",
    background: "var(--background)",
    accent: "var(--accent)",
  }

  if (theme.accentColor === undefined) {
    delete colors.accent
  }

  // 注入额外 CSS 变量作为颜色
  if (theme.cssVars) {
    for (const key of Object.keys(theme.cssVars)) {
      // --cyber-glow -> cyber-glow
      const colorKey = key.replace(/^--/, "")
      colors[colorKey] = `var(${key})`
    }
  }

  const config = {
    theme: {
      extend: {
        colors,
        borderRadius: {
          lg: "var(--radius)",
          md: "calc(var(--radius) - 2px)",
          sm: "calc(var(--radius) - 4px)",
        },
        fontFamily: theme.font
          ? {
            sans: [`var(--font-${theme.font})`, "sans-serif"],
          }
          : undefined,
      },
    },
  }

  return `// Auto-generated by yyc3 themes — ${theme.name}
export const themeConfig = ${JSON.stringify(config, null, 2)}
`
}

/**
 * 生成 globals.css 片段（含 @layer base）
 */
export function generateGlobalsCss(theme: ThemeConfig): string {
  const lines: string[] = []

  lines.push(`/* YYC³ Theme: ${theme.name} — ${theme.label} */`)
  lines.push(`/* ${theme.description} */`)
  lines.push("")

  // @layer base 主题变量
  lines.push("@layer base {")
  lines.push(`  :root[data-theme="${theme.name}"] {`)
  lines.push(`    --primary: ${theme.primaryColor};`)
  lines.push(`    --background: ${theme.backgroundColor};`)
  if (theme.accentColor) {
    lines.push(`    --accent: ${theme.accentColor};`)
  }
  if (theme.cssVars) {
    for (const [key, value] of Object.entries(theme.cssVars)) {
      lines.push(`    ${key}: ${value};`)
    }
  }
  lines.push(`    --radius: ${radiusToCss(theme.radius)};`)
  lines.push("  }")
  lines.push("")

  // body 应用
  lines.push(`  [data-theme="${theme.name}"] body {`)
  lines.push("    background-color: var(--background);")
  lines.push("    color: var(--foreground, currentColor);")
  lines.push("  }")
  lines.push("}")

  return lines.join("\n")
}

/**
 * 生成主题切换脚本（前端运行时）
 */
export function generateThemeSwitcherScript(): string {
  return `
// YYC³ Theme Switcher — Auto-generated
(function() {
  const STORAGE_KEY = 'yyc3-theme'
  const DEFAULT_THEME = 'yyc3-brand'

  function applyTheme(name) {
    document.documentElement.setAttribute('data-theme', name)
    try { localStorage.setItem(STORAGE_KEY, name) } catch (e) {}
  }

  function getCurrentTheme() {
    try { return localStorage.getItem(STORAGE_KEY) || DEFAULT_THEME } catch (e) {
      return DEFAULT_THEME
    }
  }

  function toggleDark() {
    const current = document.documentElement.getAttribute('data-theme')
    const isDark = document.documentElement.classList.contains('dark')
    if (isDark) {
      document.documentElement.classList.remove('dark')
    } else {
      document.documentElement.classList.add('dark')
    }
  }

  // Auto-apply on load
  const initial = getCurrentTheme()
  applyTheme(initial)

  // Export
  window.YYC3Theme = {
    apply: applyTheme,
    get: getCurrentTheme,
    toggleDark: toggleDark,
  }
})()
`.trim()
}

/**
 * 生成主题切换 React Hook
 */
export function generateThemeHook(): string {
  return `
import { useState, useEffect, useCallback } from 'react'

const STORAGE_KEY = 'yyc3-theme'
const DEFAULT_THEME = 'yyc3-brand'

export function useYYC3Theme() {
  const [theme, setThemeState] = useState<string>(DEFAULT_THEME)
  const [isDark, setIsDark] = useState<boolean>(false)

  useEffect(() => {
    const saved = typeof window !== 'undefined'
      ? localStorage.getItem(STORAGE_KEY) || DEFAULT_THEME
      : DEFAULT_THEME
    setThemeState(saved)
  }, [])

  const setTheme = useCallback((name: string) => {
    setThemeState(name)
    if (typeof document !== 'undefined') {
      document.documentElement.setAttribute('data-theme', name)
    }
    if (typeof window !== 'undefined') {
      try { localStorage.setItem(STORAGE_KEY, name) } catch (e) {}
    }
  }, [])

  const toggleDark = useCallback(() => {
    setIsDark((prev) => {
      const next = !prev
      if (typeof document !== 'undefined') {
        if (next) document.documentElement.classList.add('dark')
        else document.documentElement.classList.remove('dark')
      }
      return next
    })
  }, [])

  return { theme, setTheme, isDark, toggleDark }
}
`.trim()
}

